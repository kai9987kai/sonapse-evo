"""The sixteen-channel sensory contract (order matches NEUROWEAVE-LAB ``buildSensoryVector``)."""
from __future__ import annotations

import enum
from dataclasses import dataclass, field
from typing import Any, Dict, List, Tuple

from ..contracts import INTERFACE_VERSIONS, Provenance


@dataclass(frozen=True)
class ChannelSpec:
    name: str
    modality: str
    low: float
    high: float
    description: str


CHANNEL_SPECS: Tuple[ChannelSpec, ...] = (
    ChannelSpec("visual_luminance", "visual", 0.0, 1.0, "mean luminance"),
    ChannelSpec("visual_red_green", "visual", -1.0, 1.0, "red/green colour opponency"),
    ChannelSpec("visual_blue_yellow", "visual", -1.0, 1.0, "blue/yellow colour opponency"),
    ChannelSpec("visual_edge_density", "visual", 0.0, 1.0, "fraction of strong luminance edges"),
    ChannelSpec("visual_motion", "visual", 0.0, 1.0, "frame-to-frame luminance change"),
    ChannelSpec("audio_low", "auditory", 0.0, 1.0, "low-frequency spectral energy"),
    ChannelSpec("audio_mid", "auditory", 0.0, 1.0, "mid-frequency spectral energy"),
    ChannelSpec("audio_high", "auditory", 0.0, 1.0, "high-frequency spectral energy"),
    ChannelSpec("olfactory", "olfactory", 0.0, 1.0, "odour / food-gradient proxy"),
    ChannelSpec("gustatory", "gustatory", 0.0, 1.0, "taste proxy on contact with food"),
    ChannelSpec("thermosensation", "thermal", 0.0, 1.0, "local temperature"),
    ChannelSpec("interoception", "interoceptive", 0.0, 1.0, "internal energy deficit"),
    ChannelSpec("proprioception", "proprioceptive", 0.0, 1.0, "own movement speed"),
    ChannelSpec("mechanosensation", "mechanical", 0.0, 1.0, "touch / collision"),
    ChannelSpec("environment_state", "context", 0.0, 1.0, "obstacle proximity summary"),
    ChannelSpec("task_context", "context", 0.0, 1.0, "task cue"),
)
SENSORY_CHANNELS: Tuple[str, ...] = tuple(c.name for c in CHANNEL_SPECS)

#: additional derived features produced by the extractors (available for experiments and dashboards)
EXTENDED_FEATURES: Tuple[str, ...] = (
    "visual_centroid_x", "visual_centroid_y", "visual_change", "visual_object_count", "visual_object_area",
    "visual_flicker", "audio_amplitude", "audio_flux", "audio_onset", "audio_periodicity",
)


class ChannelMode(str, enum.Enum):
    ENABLED = "enabled"        # fed by live or environment input
    DISABLED = "disabled"      # reads exactly 0
    SIMULATED = "simulated"    # generated by ``SimulatedSensors``
    EXTERNAL = "external"      # supplied by an external process


@dataclass
class SensoryManifest:
    modes: Dict[str, ChannelMode] = field(default_factory=lambda: {c: ChannelMode.ENABLED for c in SENSORY_CHANNELS})
    provenance: Dict[str, str] = field(default_factory=lambda: {c: Provenance.SYNTHETIC_SIMULATION.value for c in SENSORY_CHANNELS})
    camera_enabled: bool = False
    microphone_enabled: bool = False
    version: str = INTERFACE_VERSIONS["sensory_manifest"]

    @property
    def raw_media_stored(self) -> bool:
        return False            # invariant: raw frames / audio are never retained

    def to_dict(self) -> Dict[str, Any]:
        return {"version": self.version, "channels": list(SENSORY_CHANNELS),
                "specs": [{"name": c.name, "modality": c.modality, "low": c.low, "high": c.high} for c in CHANNEL_SPECS],
                "modes": {k: ChannelMode(v).value for k, v in self.modes.items()}, "provenance": dict(self.provenance),
                "camera_enabled": bool(self.camera_enabled), "microphone_enabled": bool(self.microphone_enabled),
                "raw_media_stored": False}

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "SensoryManifest":
        manifest = cls(camera_enabled=bool(data.get("camera_enabled", False)), microphone_enabled=bool(data.get("microphone_enabled", False)))
        for name, mode in data.get("modes", {}).items():
            if name in manifest.modes:
                manifest.modes[name] = ChannelMode(mode)
        for name, prov in data.get("provenance", {}).items():
            if name in manifest.provenance:
                manifest.provenance[name] = Provenance(prov).value
        return manifest


def channel_index(name: str) -> int:
    return SENSORY_CHANNELS.index(name)


def modality_channels() -> Dict[str, List[int]]:
    out: Dict[str, List[int]] = {}
    for i, spec in enumerate(CHANNEL_SPECS):
        out.setdefault(spec.modality, []).append(i)
    return out
